/* Build shared Confluence attachments and the portable review file.
 * Plain CSS and browser JavaScript only: no runtime package install or build. Libraries use local pinned vendor files.
 */
const fs = require('node:fs');
const path = require('node:path');
const read = file => fs.readFileSync(path.join(__dirname, file), 'utf8');
const write = (file, content) => fs.writeFileSync(path.join(__dirname, file), content);
const safeScript = text => text.replace(/<\/script/gi, '<\\/script');
const sourceFiles = ['library-loader.js', 'notifications.js', 'reader-sidebar.js', 'scroll-tools.js', 'vendor/markdown-it-15.0.2.min.js', 'search.js', 'data-table.js', 'workspace-table.js', 'pagination.js', 'entitlements.js', 'ui.js', 'editor-content.js', 'document-metrics.js', 'view-counts.js', 'document-export.js', 'document-export-ui.js', 'governance.js', 'governance-ui.js', 'workflow.js', 'discovery.js', 'space-storage.js','space-access-sync.js', 'space-engagement.js', 'space-renderer.js', 'space-workflow.js', 'article-comments.js', 'space-personal.js', 'confluence.js', 'editor.js', 'navigation.js', 'workspace-charts.js', 'suggestions.js', 'add-document-widget.js', 'entitlements-page.js', 'bookmarks.js', 'content-health.js', 'space-health.js', 'health-service.js', 'content-health-ui.js', 'library-workflows.js', 'loading-overlay.js', 'insights.js', 'article-analytics-download.js', 'faq.js', 'app.js'];

// All entry points use this one stylesheet. Embedded fonts avoid extra
// attachment paths and font-network requests in the Confluence macro.
const css = ['styles.css','notifications.css','ui.css','editor-upgrade.css','video.css','workspace.css','workspace-charts.css','suggestions.css','pagination.css','add-document-widget.css','entitlements-page.css','document-metrics.css','data-table.css','document-export.css','document-export-ui.css','content-health.css','library-workflows.css','governance.css','loading-overlay.css','article-discussion.css','insights.css','page-style-flags.css','reader-sidebar.css','theme.css','landing-faq.css','credit-dashboard.css'].map(read).join('\n').replace(/url\(["']?assets\/(citi-text-(?:regular|bold)\.ttf)["']?\)/g, (_, file) =>
  'url("data:font/ttf;base64,' + fs.readFileSync(path.join(__dirname, 'assets', file)).toString('base64') + '")').replace('url("assets/citi-logo.svg")', 'url("data:image/svg+xml;base64,' + fs.readFileSync(path.join(__dirname, 'assets/citi-logo.svg')).toString('base64') + '")');
const bundle = '/* WCSpedia shared browser bundle. Generated by build.cjs. */\n' +
  sourceFiles.map(file => '\n/* Source: ' + file + ' */\n' + read(file) + '\n;').join('\n');
const brandLogoBytes = fs.readFileSync(path.join(__dirname, 'assets/wcspedia-logo.png'));
const portableBrandLogo = 'data:image/png;base64,' + brandLogoBytes.toString('base64');
// Change attachment URLs with the build so browsers cannot retain old controls.
const assetRevision = require('node:crypto').createHash('sha256').update(css).update(bundle).update(read('publication-config.js')).update(read('templates/wcspedia-document.mdx')).update(brandLogoBytes).digest('hex').slice(0,12);
write('wcspedia-style.css', css);
write('wcspedia.js', bundle);

// Keep the reader attachment separate from restricted working revisions and
// audit comments. The full JSON remains the local demonstration/control dataset.
const fullData = JSON.parse(read('wcspedia-data.json'));
write('data.js', '/* Illustrative WCSpedia content and governed version snapshots. */\nwindow.WCSData = ' + JSON.stringify(fullData, null, 2) + ';\n');
const publishedData = JSON.parse(JSON.stringify(fullData));
publishedData.taxonomyAudit = [];
delete publishedData.entitlementPolicy;
publishedData.documents = publishedData.documents.flatMap(doc => {
  const published = doc.versions.find(version => version.version === doc.publishedVersion && version.status === 'Published');
  if(published)delete published.governanceReview;
  // A reader projection must never reveal the restricted working page mapping.
  // Promote only the confirmed published page and keep one canonical alias.
  const readerPageId = doc.publishedConfluencePageId, readerPageVersion = doc.publishedConfluencePageVersion;
  delete doc.confluencePageId; delete doc.confluencePageVersion; delete doc.confluence;
  delete doc.publishedConfluencePageId; delete doc.publishedConfluencePageVersion;
  if (readerPageId != null) {
    doc.confluencePageId = readerPageId;
    if (readerPageVersion != null) doc.confluencePageVersion = readerPageVersion;
  }
  return published && !doc.deletedAt ? [Object.assign({}, doc, { versions: [published], audit: [] })] : [];
});
write('wcspedia-published.json', JSON.stringify(publishedData, null, 2) + '\n');

